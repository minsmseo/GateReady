import * as confluence from '../clients/confluence';
import { VERDICT, VERDICT_LABEL } from '../domain/ruleTypes.js';
import { getGapLinks, getResult } from '../data/results.js';
import { requirePlan, resolveGate, UserError } from '../services/checks.js';
import { nameResult } from '../services/people.js';
import { action, resolveProject } from './shared.js';

const escape = (value) =>
  String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const link = (title, url) => (url ? `<a href="${escape(url)}">${escape(title)}</a>` : escape(title));

const STATUS_COLOUR = { met: 'Green', not_met: 'Red', needs_review: 'Yellow' };
const statusMacro = (verdict) =>
  `<ac:structured-macro ac:name="status"><ac:parameter ac:name="colour">${STATUS_COLOUR[verdict] || 'Grey'}</ac:parameter><ac:parameter ac:name="title">${escape(
    VERDICT_LABEL[verdict] || verdict
  )}</ac:parameter></ac:structured-macro>`;

/** Builds the page body (Confluence storage format). */
const buildBody = ({ project, gate, result, gaps, notes }) => {
  const { summary } = result;
  const row = (item) => {
    const gap = gaps[item.requirementId];
    const evidence = item.evidence.length ? item.evidence.map((e) => `${link(e.title, e.url)}${e.detail ? ` (${escape(e.detail)})` : ''}`).join('<br/>') : '-';
    return `<tr><td>${escape(item.title)}</td><td>${statusMacro(item.verdict)}</td><td>${escape(item.reason)}</td><td>${evidence}</td><td>${escape(
      item.owner?.displayName || 'No owner'
    )}</td><td>${gap ? link(gap.issueKey, `${project.siteUrl}/browse/${gap.issueKey}`) : '-'}</td></tr>`;
  };
  const list = (items) => (items.length ? `<ul>${items.map((item) => `<li><strong>${escape(item.title)}</strong>: ${escape(item.reason)}</li>`).join('')}</ul>` : '<p>None.</p>');

  const notMet = result.items.filter((item) => item.verdict === VERDICT.NOT_MET);
  const review = result.items.filter((item) => item.verdict === VERDICT.NEEDS_REVIEW);
  const recommendation =
    summary.notMet > 0
      ? `Not ready: ${summary.notMet} requirement(s) are not met.`
      : summary.needsReview > 0
        ? `Evidence is in place, but ${summary.needsReview} item(s) need a reviewer's judgement before the gate decision.`
        : 'Ready: all evidence requirements are met.';

  return [
    `<p><em>Draft generated by GateReady from the check on ${escape(result.checkedAt.slice(0, 16).replace('T', ' '))} UTC. Verdicts come from deterministic rules over live Jira and Confluence data.</em></p>`,
    '<h2>Readiness</h2>',
    `<p><strong>${escape(project.projectName)} (${escape(project.projectKey)}) - ${escape(gate.name)} gate</strong></p>`,
    `<p>${summary.readiness}% ready: ${summary.met} of ${summary.total} requirements met, ${summary.notMet} not met, ${summary.needsReview} need review.</p>`,
    `<p><strong>${escape(recommendation)}</strong></p>`,
    '<h2>Open gaps</h2>',
    list(notMet),
    '<h2>Items for reviewer judgement</h2>',
    list(review),
    '<h2>Evidence checklist</h2>',
    '<table><tbody><tr><th>Requirement</th><th>Verdict</th><th>Finding</th><th>Evidence</th><th>Owner</th><th>Gap work item</th></tr>',
    result.items.map(row).join(''),
    '</tbody></table>',
    notes
      ? `<h2>Reviewer notes (advisory)</h2><p><em>Observations added by the Gate Review Agent. They are opinions for the review meeting and do not change any verdict above.</em></p><p>${escape(
          notes
        ).replace(/\n/g, '<br/>')}</p>`
      : '',
    '<h2>Decision</h2>',
    '<p>Decision: </p><p>Conditions: </p><p>Attendees: </p>',
  ].join('');
};

/**
 * draft-gate-review-summary: writes the latest check of a gate into a
 * Confluence draft page for the gate review meeting. The page is created
 * as an unpublished draft in the project's linked space; the user reviews
 * and publishes it themselves.
 */
export const draftGateReviewSummary = action('draft-gate-review-summary', async (payload) => {
  const project = await resolveProject(payload);
  const plan = await requirePlan(project.projectId);
  const gate = resolveGate(plan, payload.gate);
  const stored = await getResult(project.projectId, gate.id);
  if (!stored) throw new UserError(`The ${gate.name} gate has not been checked yet. Run a gate check first.`);
  const result = await nameResult(stored);
  if (!plan.spaceKey) throw new UserError('No Confluence space is linked to this project. Set one in Project settings > GateReady settings.');

  const space = await confluence.getSpaceByKey(plan.spaceKey);
  if (!space) throw new UserError(`Confluence space ${plan.spaceKey} does not exist or you do not have access to it.`);

  const gaps = await getGapLinks(project.projectId);
  const notes = String(payload.reviewerNotes || '').trim().slice(0, 4000);
  const stamp = new Date().toISOString().slice(0, 16).replace('T', ' ');
  const page = await confluence.createPage({
    spaceId: space.id,
    parentId: space.homepageId,
    title: `Gate Review Summary - ${gate.name} - ${stamp} UTC`,
    storage: buildBody({ project, gate, result, gaps, notes }),
    draft: true,
  });

  return {
    created: { title: page.title, url: page.url, space: plan.spaceKey, state: 'Unpublished draft' },
    basedOnCheckAt: result.checkedAt,
    note: 'The page is an unpublished draft visible to the current user. They should review it and publish it from Confluence.',
  };
});
