/**
 * Demo scenario. Everything here is fictional: the supplier ("Norvale
 * Precision Components"), the customer ("Altamira Motors"), the parts and
 * every number. Only generic APQP/PPAP terms are used.
 *
 * Two projects use the same APQP template and sit at the same gate
 * (Process Design) but have different evidence, so they get different
 * readiness results:
 *   BSH  Brake Sensor Housing  - almost ready (one empty PFMEA section)
 *   EVB  EV Battery Bracket    - PFMEA not approved, Control Plan older than
 *                                the last design change, MSA plan missing,
 *                                open tasks and two unresolved high-risk items
 */

const h = (title, ...paragraphs) => `<h2>${title}</h2>${paragraphs.map((text) => `<p>${text}</p>`).join('')}`;
const intro = (text) => `<p><em>Demo document generated by GateReady. All names and data are fictional.</em></p><p>${text}</p>`;

const APPROVED = { name: 'Approved', color: '#36B37E' };
const IN_PROGRESS = { name: 'In progress', color: '#2684FF' };

const fmeaBody = (part, kind, { emptyActions = false } = {}) =>
  [
    intro(`${kind} for the ${part}, prepared by the cross-functional team at Norvale Precision Components for Altamira Motors.`),
    h(kind === 'DFMEA' ? 'Function' : 'Process Step',
      kind === 'DFMEA'
        ? `The ${part} locates and protects the component and keeps its position within tolerance over the vehicle life.`
        : `Operations 10 to 60: incoming inspection, forming, joining, surface treatment, final inspection and packing of the ${part}.`),
    h('Failure Mode', 'Mounting face out of flatness; fastener boss cracked; sealing surface porosity; dimensional drift after surface treatment.'),
    h('Effects', 'Loss of position accuracy, water ingress, or rework at the customer line. Highest severity rating in this study is 8.'),
    h('Causes', 'Tool wear, incorrect clamping force, material lot variation, and bath concentration outside the control window.'),
    h('Current Controls', 'In-process gauging at every 50th part, clamping force monitoring with automatic stop, and lot traceability by label scan.'),
    emptyActions
      ? h('Recommended Actions', 'TBD')
      : h('Recommended Actions', 'Add a poka-yoke locator at operation 20; shorten the tool change interval; review ratings again after the production trial run.'),
  ].join('');

const controlPlanBody = (part, revision) =>
  [
    intro(`Pre-launch Control Plan for the ${part}, revision ${revision}.`),
    h('Characteristics', 'Mounting face flatness, boss diameter, hole position, coating thickness and visual appearance.'),
    h('Measurement Method', 'Coordinate measuring machine for dimensions, eddy current gauge for coating thickness, visual standard for appearance.'),
    h('Sample Size and Frequency', 'Five parts at start of shift and after every tool change; coating thickness on one part per rack.'),
    h('Reaction Plan', 'Stop the operation, quarantine parts since the last good check, notify the quality engineer and record the event.'),
  ].join('');

const simpleBody = (text, ...sections) => [intro(text), ...sections].join('');

/** Pages for one project. `state` is the Confluence page status to set. */
const pages = (part, { pfmeaState, pfmeaEmptyActions, controlPlanRevision, withMsa }) => [
  { label: 'program-plan', title: `${part} - Program Plan`, state: APPROVED,
    body: simpleBody(`Program timing and responsibilities for the ${part}.`, h('Milestones', 'Gate reviews follow the five APQP phases. Start of production is planned after the Validation gate.'), h('Team', 'Program management, design, manufacturing engineering, quality and purchasing.')) },
  { label: 'customer-requirements', title: `${part} - Customer Requirements`, state: APPROVED,
    body: simpleBody(`Requirements received from Altamira Motors for the ${part}.`, h('Functional Requirements', 'Fit, sealing and durability targets as agreed in the sourcing package.'), h('Quality Targets', 'Zero defects at the customer line during launch; capability index of at least 1.67 for special characteristics.')) },
  { label: 'dfmea', title: `${part} - DFMEA`, state: APPROVED, body: fmeaBody(part, 'DFMEA') },
  { label: 'dvp', title: `${part} - Design Verification Plan`, state: APPROVED,
    body: simpleBody(`Design verification plan and report for the ${part}.`, h('Tests', 'Vibration, thermal cycling, salt spray and dimensional stability.'), h('Results', 'All tests passed on design-intent samples.')) },
  { label: 'process-flow', title: `${part} - Process Flow Diagram`, state: APPROVED,
    body: simpleBody(`Process flow for the ${part}.`, h('Flow', 'Receiving, forming, joining, surface treatment, final inspection, packing and shipping.'), h('Special Characteristics', 'Marked at operations 20 and 40.')) },
  { label: 'pfmea', title: `${part} - PFMEA`, state: pfmeaState, body: fmeaBody(part, 'PFMEA', { emptyActions: pfmeaEmptyActions }) },
  { label: 'control-plan', title: `${part} - Control Plan`, state: APPROVED, body: controlPlanBody(part, controlPlanRevision) },
  ...(withMsa
    ? [
        { label: 'msa-plan', title: `${part} - MSA Plan`, state: APPROVED,
          body: simpleBody(`Measurement system analysis plan for the ${part}.`, h('Gauges in Scope', 'Coordinate measuring machine, coating thickness gauge and go/no-go gauges.'), h('Studies', 'Gauge repeatability and reproducibility studies with ten parts, three appraisers and three trials.')) },
        { label: 'msa-report', title: `${part} - MSA Report`, state: IN_PROGRESS,
          body: simpleBody(`Measurement system analysis results for the ${part}.`, h('Results', 'Studies are scheduled during the production trial run.')) },
      ]
    : []),
];

/** Work items. `gate` becomes the label gate-N; `risk` adds the high-risk label. */
const task = (summary, gate, done, risk = false) => ({ summary, labels: [`gate-${gate}`, ...(risk ? ['high-risk'] : [])], done });

const earlyTasks = [
  task('Confirm customer requirements and special characteristics', 1, true),
  task('Agree program timing with the customer', 1, true),
  task('Close design review actions', 2, true),
  task('Release drawings for tooling', 2, true),
];

